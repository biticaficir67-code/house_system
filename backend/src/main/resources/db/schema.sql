CREATE TABLE IF NOT EXISTS sys_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(64) NOT NULL,
    phone VARCHAR(32),
    role VARCHAR(32) NOT NULL DEFAULT 'AGENT',
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS owner (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    id_number VARCHAR(64),
    remark VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS house (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT,
    title VARCHAR(128) NOT NULL,
    city VARCHAR(32) NOT NULL,
    district VARCHAR(32),
    community_name VARCHAR(128) NOT NULL,
    business_area VARCHAR(128),
    building_area_sqm DECIMAL(10,2) NOT NULL,
    rooms SMALLINT NOT NULL,
    halls SMALLINT NOT NULL DEFAULT 0,
    bathrooms SMALLINT NOT NULL DEFAULT 0,
    floor_level VARCHAR(16),
    total_floors SMALLINT,
    orientation VARCHAR(128) NOT NULL DEFAULT '[]',
    decoration VARCHAR(16),
    building_type VARCHAR(32),
    has_elevator BOOLEAN,
    property_usage VARCHAR(32),
    listing_price_yuan DECIMAL(16,2),
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING_REVIEW',
    core_selling VARCHAR(4000),
    community_intro VARCHAR(4000),
    surrounding VARCHAR(4000),
    analysis_summary VARCHAR(2000),
    analysis_advantages CLOB,
    analysis_disadvantages CLOB,
    analysis_word_freq CLOB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_house_status_created ON house(status, created_at);
CREATE INDEX IF NOT EXISTS idx_house_community ON house(community_name);

CREATE TABLE IF NOT EXISTS customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL,
    phone VARCHAR(32),
    budget_min_yuan DECIMAL(16,2),
    budget_max_yuan DECIMAL(16,2),
    desired_districts VARCHAR(1000),
    desired_communities VARCHAR(1000),
    rooms_min SMALLINT,
    rooms_max SMALLINT,
    tags CLOB,
    assigned_agent_id BIGINT,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(2000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS house_show (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    house_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    agent_id BIGINT NOT NULL,
    appointment_at TIMESTAMP NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'SCHEDULED',
    feedback VARCHAR(2000),
    follow_up_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_house_show_agent_time ON house_show(agent_id, appointment_at);
